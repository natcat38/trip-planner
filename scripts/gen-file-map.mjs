#!/usr/bin/env node
/**
 * Generate FILE-MAP.md — the directory index agents jump to instead of crawling.
 *
 * Descriptions are pulled from what the code already declares (a TSDoc
 * `@packageDocumentation` block), so there is nothing extra to keep in sync:
 * change the block, regenerate, done. Directories with no such declaration
 * render an empty Purpose, which makes the undocumented corners visible
 * rather than inventing prose for them.
 *
 * Ported from f1-race-tracker's scripts/gen_file_map.py, trimmed to the
 * TSDoc reader only (no Go/Python toolchain in this repo) and implemented
 * in zero-dependency Node so it runs with nothing beyond the Node already
 * required to run this project.
 *
 *   node scripts/gen-file-map.mjs            # rewrite FILE-MAP.md
 *   node scripts/gen-file-map.mjs --check    # exit 1 if FILE-MAP.md is stale (CI)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ROOT, 'FILE-MAP.md');

// Trees worth mapping, in reading order. Everything else (node_modules,
// .next, build output, caches) is deliberately absent — the map is for
// hand-authored source.
const ROOTS = ['src', 'e2e', 'prisma'];
const SOURCE_SUFFIXES = ['.ts', '.tsx', '.mts'];
const SKIP_DIR_PARTS = new Set([
  'node_modules',
  '.next',
  'test-results',
  'migrations',
]);

// src/generated/prisma is Prisma's generated client output — machine-written,
// re-created by `prisma generate` on every install, and never hand-edited.
// Requiring a @packageDocumentation block there would just mean editing
// generated code (which gets clobbered) or lying about authorship, so the
// whole subtree is excluded rather than merely undocumented.
const SKIP_PATH_PREFIXES = ['src/generated'];

function isTestFile(name) {
  return /\.(test|spec)\.[cm]?tsx?$/.test(name) || name.includes('__tests__');
}

/**
 * First `/** ... @packageDocumentation *‍/` block in a .ts/.tsx/.mts file.
 *
 * TSDoc's @packageDocumentation is the direct analogue of Go's `// Package x`
 * or a Python module docstring: it marks a comment as describing the whole
 * module rather than the next symbol.
 */
function tsDoc(dirPath, files) {
  // Entry-point files (route/page/layout/index) describe the directory as a
  // whole; any other file's block describes just that file. Try entries first
  // so a route tree isn't summarised by whichever component sorts first.
  const isEntry = (f) => /^(index|page|layout|route)\.[cm]?tsx?$/.test(f);
  const candidates = files
    .filter((f) => SOURCE_SUFFIXES.some((s) => f.endsWith(s)) && !isTestFile(f))
    .sort(
      (a, b) => Number(isEntry(b)) - Number(isEntry(a)) || a.localeCompare(b),
    );
  for (const f of candidates) {
    const src = readFileSync(join(dirPath, f), 'utf8');
    // Not anchored to file start: a leading "use client"/"use server"
    // directive (which must stay the literal first line) can precede the
    // doc block, so this matches the first qualifying comment wherever it
    // sits near the top of the file.
    const m = src.match(/\/\*\*([\s\S]*?)\*\//);
    if (m && m[1].includes('@packageDocumentation')) {
      const body = m[1].replace('@packageDocumentation', '');
      const text = body
        .split('\n')
        .map((ln) => ln.trim().replace(/^\*/, '').trim())
        .filter(Boolean)
        .join(' ');
      if (text) return firstSentence(text);
    }
  }
  return '';
}

function firstSentence(text) {
  const collapsed = text.split(/\s+/).filter(Boolean).join(' ');
  if (!collapsed) return '';
  const cut = collapsed.split(/(?<=[.!?])\s/)[0];
  return cut.slice(0, 1).toUpperCase() + cut.slice(1);
}

function walk(dir, out) {
  const entries = readdirSync(dir, { withFileTypes: true });
  const files = [];
  const subdirs = [];
  for (const e of entries) {
    if (e.isDirectory()) {
      if (SKIP_DIR_PARTS.has(e.name)) continue;
      subdirs.push(e.name);
    } else if (e.isFile()) {
      files.push(e.name);
    }
  }

  const relPath = relative(ROOT, dir).split(sep).join('/');
  if (
    !SKIP_PATH_PREFIXES.some(
      (p) => relPath === p || relPath.startsWith(p + '/'),
    )
  ) {
    const sourceFiles = files.filter(
      (f) => SOURCE_SUFFIXES.some((s) => f.endsWith(s)) && !isTestFile(f),
    );
    if (sourceFiles.length) {
      out.push([relPath, sourceFiles.length, tsDoc(dir, sourceFiles)]);
    }
  }

  for (const name of subdirs.sort()) {
    walk(join(dir, name), out);
  }
}

function collectDirs() {
  const out = [];
  for (const r of ROOTS) {
    const base = join(ROOT, r);
    try {
      if (!statSync(base).isDirectory()) continue;
    } catch {
      continue;
    }
    walk(base, out);
  }
  return out;
}

function render() {
  const rows = collectDirs();
  const out = [
    '# FILE-MAP',
    '',
    'Generated by `scripts/gen-file-map.mjs` — **do not hand-edit.**',
    "Purpose comes from each directory's own TSDoc `@packageDocumentation` block,",
    'so it cannot drift from the code. Regenerate with',
    '`node scripts/gen-file-map.mjs`; CI fails if this file is stale.',
    '',
    'A blank Purpose means that directory declares no `@packageDocumentation`',
    'block — an orientation gap, not an omission by the generator.',
    '',
    '| Directory | Source files | Purpose |',
    '| --- | ---: | --- |',
  ];
  for (const [path, n, desc] of rows) {
    out.push(`| \`${path}\` | ${n} | ${desc} |`);
  }
  out.push(
    '',
    `${rows.length} source directories, ` +
      `${rows.reduce((s, [, n]) => s + n, 0)} files, ` +
      `${rows.filter(([, , d]) => !d).length} without a declared purpose.`,
    '',
  );
  return out.join('\n');
}

function main() {
  const text = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // FILE-MAP.md doesn't exist yet — treated as stale below.
    }
    if (current !== text) {
      console.log('FILE-MAP.md is stale - run: node scripts/gen-file-map.mjs');
      process.exit(1);
    }
    console.log('FILE-MAP.md is current');
    process.exit(0);
  }
  // Write with explicit "\n" line endings (never Node's platform default) so
  // the file is byte-identical whether generated on Windows or in CI, and
  // --check never trips on a CRLF/LF mismatch.
  writeFileSync(OUT, text, { encoding: 'utf8' });
  console.log(`wrote ${relative(ROOT, OUT).split(sep).join('/')}`);
}

main();
